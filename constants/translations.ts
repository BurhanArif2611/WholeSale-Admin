/** English base merged into every locale so missing keys never show raw key names. */
function mergeTranslationsWithFallback(
  raw: Record<Locale, Record<string, string>>,
): Record<Locale, Record<string, string>> {
  const base = raw.en ?? {};
  const merged = {} as Record<Locale, Record<string, string>>;
  (Object.keys(raw) as Locale[]).forEach((locale) => {
    merged[locale] = { ...base, ...raw[locale] };
  });
  return merged;
}

